def check(save):
    stats = save.get("stats", {})
    claimed = save.get("ach", [])
    if not isinstance(claimed, list):
        claimed = []
    claimed_set = set(claimed)
    granted = []
    for a in ACHIEVEMENTS:
        if a["id"] in claimed_set:
            continue
        if stats.get(a["stat"], 0) >= a["goal"]:
            claimed.append(a["id"])
            save["coins"] = save.get("coins", 0) + a["reward"]
            if a.get("gems"):
                save["gems"] = save.get("gems", 0) + a["gems"]
                save["stats"]["gems_earned"] = save.get("stats", {}).get("gems_earned", 0) + a["gems"]
            granted.append(a)
    if granted:
        save["ach"] = claimed
    return granted
